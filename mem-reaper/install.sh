#!/usr/bin/env bash
# mem-reaper installer (macOS): a per-user LaunchAgent that runs reaper.py every 2 minutes. Idempotent.
#   ./install.sh              install or update
#   ./install.sh --check      show status + last log lines
#   ./install.sh --uninstall  remove the LaunchAgent and the deployed copy
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
[ "$(uname -s)" = "Darwin" ] || { echo "macOS only"; exit 1; }
UID_=$(id -u); LABEL="com.sandesh.mem-reaper"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
DEST="$HOME/.local/share/mem-reaper"; LOG="$HOME/Library/Logs/mem-reaper.log"
case "${1:-}" in
  --check) launchctl print "gui/$UID_/$LABEL" 2>&1 | grep -E 'state =|runs =|last exit' || echo "not loaded"; tail -8 "$LOG" 2>/dev/null; exit 0 ;;
  --uninstall) launchctl bootout "gui/$UID_/$LABEL" 2>/dev/null || true; rm -rf "$PLIST" "$DEST"; echo removed; exit 0 ;;
esac
# deployed copy outside ~/Documents (launchd can't always open files there, see cptr-watchdog)
mkdir -p "$DEST"; cp "$HERE/reaper.py" "$DEST/reaper.py"; chmod +x "$DEST/reaper.py"
xattr -d com.apple.provenance "$DEST/reaper.py" 2>/dev/null || true
cat > "$PLIST" <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  <!-- Generated by agent-tools/mem-reaper/install.sh -->
  <key>ProgramArguments</key><array><string>/usr/bin/python3</string><string>$DEST/reaper.py</string></array>
  <key>StartInterval</key><integer>120</integer>
  <key>RunAtLoad</key><true/>
  <key>ProcessType</key><string>Background</string>
  <key>StandardOutPath</key><string>/tmp/mem-reaper.out</string>
  <key>StandardErrorPath</key><string>/tmp/mem-reaper.out</string>
</dict></plist>
PL
launchctl bootout "gui/$UID_/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$UID_" "$PLIST"
echo "installed $LABEL (every 2 min; full clean-up every 30 min or at swap > 20 GB). Log: $LOG"
